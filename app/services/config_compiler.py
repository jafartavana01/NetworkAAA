"""
app.services.config_compiler
==============================
This is the component spec section 13 calls "one of the most important
architectural components": it turns PostgreSQL state into a candidate
tac_plus-ng configuration, validates it, computes a diff against
what's actually live on disk, and -- only on explicit confirmation --
backs up, applies, reloads, health-checks, and auto-rolls-back on
failure (sections 14-15, 34).

NOTE ON DUPLICATION: the static preamble (spawnd block + log targets)
below is intentionally kept textually identical to
installer/bootstrap_config.py's template. That installer module runs
at install time, before this application package is even copied to
/opt/aaa-platform, so the two can't share a live import -- see
docs/ARCHITECTURE.md for why they're two files, not one.
"""
