class ConfigCompilerError(RuntimeError):
    pass


class UncompilablePolicyError(RuntimeError):
    """
    Raised when a policy's condition tree contains something with no
    confirmed tac_plus-ng syntax to compile it into -- per the pasted
    condition-builder spec's explicit "if something cannot be
    represented safely in tac_plus-ng, do NOT fake it" instruction.
    The caller (compile_candidate) catches this PER POLICY and
    excludes just that one policy from the generated ruleset entirely
    -- it simply never matches anything in the compiled config, which
    is the safe, deny-leaning failure mode this project has used
    consistently since Phase 5, not a silently-wrong or partially-fake
    compilation. compile_candidate() also records an InstallEvent for
    every exclusion, so this is auditable, not a silent gap.
    """
    pass


class ApplyFailedError(RuntimeError):
    def __init__(self, message: str, journal: str = ""):
        super().__init__(message)
        self.journal = journal


def _quote(value: str) -> str:
    """Double-quote a config value, escaping backslashes and quotes.
    Used only for values (shared secrets); device *names* are never
    passed through this -- see app.schemas.device for why identifiers
    are restricted at input time instead of escaped."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _mavis_block(settings: AdSettings | None) -> str:
    """
    Active Directory / MAVIS integration (confirmed real syntax --
    directly confirmed via a real tac_plus-ng-specific config, shebang
    literally `#!/usr/local/sbin/tac_plus-ng`, on the project's own
    mailing list: `mavis module = external { setenv ... exec = ... }`
    nested directly inside `id = tac_plus-ng {}`, with `login backend
    = mavis` / `user backend = mavis` as sibling top-level directives.
    LDAP_SERVER_TYPE / LDAP_HOSTS / LDAP_BASE / LDAP_USER / LDAP_PASSWD
    / LDAP_FILTER / LDAP_SCOPE / FLAG_USE_MEMBEROF / AD_GROUP_PREFIX
    all appeared consistently across multiple independent real
    configs. Deliberately NOT emitting a REQUIRE_*_GROUP_PREFIX
    directive: sources disagreed on its exact name
    (REQUIRE_AD_GROUP_PREFIX vs REQUIRE_TACACS_GROUP_PREFIX) and it's
    optional, so omitting it avoids guessing between two names found
    in different sources rather than picking one and hoping.

    Returns "" (no MAVIS block at all, local-only authentication
    continues exactly as before) when AD integration isn't enabled or
    has no host configured -- this is what makes AD integration purely
    additive: an install that never touches this setting compiles an
    identical config to before this feature existed.
    """
    if settings is None or not settings.enabled or not settings.host:
        return ""

    password = ""
    if settings.bind_password_encrypted:
        password = security.decrypt_secret(settings.bind_password_encrypted)

    lines = ["    mavis module = external {"]
    lines.append('        setenv LDAP_SERVER_TYPE = "microsoft"')
    scheme = "ldaps" if settings.use_tls else "ldap"
    lines.append(f'        setenv LDAP_HOSTS = "{scheme}://{settings.host}:{settings.port}"')
    lines.append("        setenv LDAP_SCOPE = sub")
    if settings.search_base:
        lines.append(f"        setenv LDAP_BASE = {_quote(settings.search_base)}")
    if settings.user_filter_template:
        lines.append(f"        setenv LDAP_FILTER = {_quote(settings.user_filter_template)}")
    if settings.bind_dn:
        lines.append(f"        setenv LDAP_USER = {_quote(settings.bind_dn)}")
    if password:
        lines.append(f"        setenv LDAP_PASSWD = {_quote(password)}")
    if settings.group_prefix:
        lines.append(f"        setenv AD_GROUP_PREFIX = {_quote(settings.group_prefix)}")
    if settings.use_memberof:
        lines.append("        setenv FLAG_USE_MEMBEROF = 1")
    lines.append("        exec = /usr/local/lib/mavis/mavis_tacplus_ads.pl")
    lines.append("    }")
    lines.append("")
    lines.append("    login backend = mavis")
    lines.append("    user backend = mavis")
    lines.append("")

    return "\n".join(lines) + "\n"


def _host_block(device: NetworkDevice) -> str:
    secret = security.decrypt_secret(device.shared_secret_encrypted)
    lines = [f"    host {device.name} {{"]
    lines.append(f"        address = {device.ip_address}")
    if device.ipv6_address:
        # NOT emitted as a directive: no IPv6-specific `host` block
        # syntax (e.g. a hypothetical `address6 =`) was confirmed
        # against upstream docs/samples during research, and inventing
        # one here would be exactly the "policy that doesn't translate
        # correctly to the core" spec section 20 warns against. The
        # value is still stored and shown in the GUI so it's not lost,
        # and surfaced as a comment so it's visible to anyone reading
        # the generated file, pending confirmation of real syntax.
        lines.append(f"        # ipv6_address on file (not yet emitted, syntax unconfirmed): {device.ipv6_address}")
    lines.append(f"        key = {_quote(secret)}")
    lines.append("    }")
    return "\n".join(lines) + "\n"


_MONITORING_CATCHALL_NAME = "world"


def _monitoring_host_block(placeholder_key: str) -> str:
    """
    "Monitoring mode" (see app.models.monitoring_settings for the full
    design reasoning). `address = ::/0` as a catch-all is confirmed
    real syntax -- seen in a real tac_plus-ng-specific working config
    on the project's own mailing list (shebang literally
    `#!/usr/local/sbin/tac_plus-ng`), and reused here with this
    project's own already-proven `host NAME { }` block structure
    (without `=` before the name -- this project's existing device
    host blocks confirmed that convention independently; some legacy
    tac_plus examples found elsewhere use `host = world { }`, but this
    project trusts its own already-working syntax over a possibly
    different generation's convention).

    ALWAYS emitted LAST relative to every specific device host block
    (see compile_candidate's call site) -- see the model docstring for
    why this makes the feature safe regardless of which host-matching
    precedence tac_plus-ng actually uses, which was not independently
    confirmed either way.

    `placeholder_key` is never a real device's actual secret -- a real
    device connecting through this catch-all will fail decryption
    against it, which is expected and is exactly what makes the
    attempt detectable (see app.services.monitoring).
    """
    lines = [f"    host {_MONITORING_CATCHALL_NAME} {{"]
    lines.append("        address = ::/0")
    lines.append(f"        key = {_quote(placeholder_key)}")
    lines.append("    }")
    return "\n".join(lines) + "\n"


def _user_block(user: TacacsUser, group_name: str | None) -> str:
    """
    Syntax confirmed against a real, working tac_plus-ng configuration
    (not legacy tac_plus, which uses different, incompatible
    directives -- `login = des <hash>` there vs `password login =
    crypt <hash>` here) posted by a user on the project's own support
    forum, with the maintainer replying in the same thread without
    correcting the syntax. `crypt` expects a standard libc crypt()
    hash; bcrypt's `$2b$`/`$2y$`-prefixed output (what
    app.security.hash_password already produces for platform admins)
    is a standard crypt() format, and Ubuntu's default libcrypt
    (libxcrypt since 20.04) supports verifying it. This was confirmed
    end-to-end against a real installation in Phase 3.

    `member = <group>` (Phase 4) uses the exact same confirmed sample
    (`user test1 { password login = clear secret member = admins }`).
    Only ever emitted when the user actually has a group -- Phase 5's
    authorization engine is what gives group membership real teeth via
    `if (member == ...)` in ruleset scripts, but the membership itself
    is real, generated config today, not a placeholder.

    The hash is emitted unquoted, matching the real-world example this
    was confirmed against. This is safe, not just convenient: crypt()
    hash output (including bcrypt) only ever uses the fixed alphabet
    `./0-9A-Za-z` plus `$` as a field separator -- never `{`, `}`,
    `"`, `#`, or whitespace -- so there's no config-injection surface
    here the way there would be for an arbitrary user-supplied string.
    """
    lines = [f"    user {user.username} {{"]
    lines.append(f"        password login = crypt {user.password_hash}")
    if group_name:
        lines.append(f"        member = {group_name}")
    lines.append("    }")
    return "\n".join(lines) + "\n"


def _group_block(group: TacacsGroup) -> str:
    """
    Confirmed valid as an EMPTY block against the same real-world
    sample (`group admins { }`, `group ad-admins { }` both appeared
    with no body). Actual permission content lives in Phase 5's
    `profile {}`/`ruleset {}` blocks, which reference group membership
    via `if (member == <group>)` -- the group itself is just the named
    bucket users get sorted into.
    """
    return f"    group {group.name} {{\n    }}\n"


def _policy_block(policy: Policy, ordered_rules: list) -> str:
    """
    Confirmed against FOUR independent real tac_plus-ng configs (see
    app/models/policy.py): the outer structure --

        profile <name> {
            script {
                if (service == shell) {
                    if (cmd == "") {
                        set priv-lvl = <N>
                    }
                    permit-or-deny-statements...
                }
            }
        }

    -- is real, working syntax. What's NOT independently confirmed the
    same way is matching a SPECIFIC command name via `cmd =~
    /pattern/` for the CommandRule entries below (see
    app/models/command_rule.py's docstring for exactly what is and
    isn't verified here).

    `ordered_rules` is expected pre-flattened and deny-first ordered
    by app.services.policy_engine.get_ordered_rules_for_policy --
    this function no longer does that ordering itself (PAM Expansion
    Plan Increment 1: rules now come from every CommandSet the policy
    references, not one owned list), specifically so the compiler and
    the Simulator/Effective-Access engine can never independently
    drift on what "deny-first" means. The policy's own default_action
    is the trailing, unconditional fallback for anything no rule
    matched.
    """
    lines = [f"    profile {policy.name} {{"]
    lines.append("        script {")
    lines.append("            if (service == shell) {")
    lines.append("                if (cmd == \"\") {")
    lines.append(f"                    set priv-lvl = {policy.default_priv_lvl}")
    lines.append("                }")

    for rule in ordered_rules:
        # command_pattern is validated as a real regex at input time
        # (app.schemas.command_set) but is otherwise arbitrary admin-
        # supplied text -- unlike identifiers, it legitimately needs
        # to contain regex metacharacters, so it's placed inside a
        # PCRE delimiter (/.../ ) rather than restricted to a safe
        # charset. It is NOT interpolated into anything that could
        # break out of the surrounding script block: tac_plus-ng's own
        # regex delimiter is what bounds it, the same way _quote()
        # bounds shared secrets with double quotes elsewhere in this
        # file.
        lines.append(f"                if (cmd =~ /{rule.command_pattern}/) {{ {rule.action} }}")
    lines.append(f"                {policy.default_action}")
    lines.append("            }")
    lines.append("        }")
    lines.append("    }")
    return "\n".join(lines) + "\n"


def _condition_expression(
    policy: Policy,
    *,
    group_names_by_id: dict,
    device_names_by_id: dict,
    device_names_by_group_id: dict,
) -> str | None:
    """
    LEGACY model only (see resolve_condition_expression below for the
    dispatch between this and the new condition-tree compiler).
    Translates a Policy's condition_* fields (PAM Expansion Plan §4)
    into a tac_plus-ng script boolean expression, combining multiple
    conditions on the same policy with `&&`. Returns None when the
    policy has no conditions at all -- such a policy matches
    unconditionally (see _ruleset_block for how that's emitted, since
    an unconditional rule needs no `if` wrapper at all).

    `member == <group>` and `device == <hostname>` are both confirmed
    real syntax (see app/models/policy.py's docstring for sources).
    Device-GROUP targeting has no native tac_plus-ng concept (same
    finding as Phase 4's Device Groups), so it's expanded here into a
    generated OR-chain of individual `device == ...` checks -- real
    syntax, generated rather than native, exactly as planned.
    """
    clauses = []

    if policy.condition_group_id is not None:
        group_name = group_names_by_id.get(policy.condition_group_id)
        if group_name:
            clauses.append(f"member == {group_name}")

    if policy.condition_device_id is not None:
        device_name = device_names_by_id.get(policy.condition_device_id)
        if device_name:
            clauses.append(f"device == {device_name}")

    if policy.condition_device_group_id is not None:
        member_device_names = device_names_by_group_id.get(policy.condition_device_group_id, [])
        if member_device_names:
            or_chain = " || ".join(f"device == {name}" for name in member_device_names)
            clauses.append(f"({or_chain})" if len(member_device_names) > 1 else or_chain)

    if not clauses:
        return None
    return " && ".join(clauses)


def _compile_condition_leaf(
    condition: PolicyCondition,
    *,
    group_names_by_id: dict,
    device_names_by_id: dict,
    device_names_by_group_id: dict,
    acl_blocks_out: list[str],
) -> str:
    """
    Compiles ONE condition-tree leaf into real tac_plus-ng syntax, or
    raises UncompilablePolicyError. Confidence per construct (see
    docs/ARCHITECTURE.md for the sourcing):

    - `member == <name>` / `device == <name>` -- CONFIRMED (same
      sources as the legacy _condition_expression above).
    - `member != <name>` / `device != <name>` / `nac != <name>` --
      REASONED, not directly observed for these specific comparisons:
      a real event-driven-servers mailing-list thread confirms tac_plus
      -ng accepts `!=` for ACL comparisons generally (a parser bug that
      had blocked it was explicitly fixed), and every `if()` expression
      in this scripting language shares one grammar (the same thread's
      own example combines an ACL check and a `member ==` check with
      `&&` in a single expression) -- so `!=` extending to member/device
      comparisons the same way `==` already does is a reasoned
      extension of confirmed behavior, not a guess from nothing.
    - `nac == <cidr>` inside an `acl { }` block, referenced via
      `acl == <name>` -- CONFIRMED directly: a real example
      (`acl alu_tl_mbh { if (nac == 10.27.64.0/21) permit deny }`,
      referenced as `if (acl == alu_tl_mbh && member == region)`)
      shows exactly this CIDR-range-via-== pattern working inside an
      ACL block specifically. is_not_in_cidr negates at the REFERENCE
      point (`acl != <name>`) rather than guessing at a differently
      -negated internal ACL check that hasn't been directly observed,
      to stay as close as possible to the one confirmed example.
    - Direct per-user matching (`user` object type, any operator) --
      NOT compilable. Every confirmed real tac_plus-ng example matches
      via `member == <group>`, never a bare username.
    """
    obj_type = condition.object_type
    op = condition.operator

    if obj_type == "user":
        raise UncompilablePolicyError(
            "Direct per-user conditions have no confirmed tac_plus-ng syntax and cannot be compiled -- "
            "target the user's group instead."
        )

    elif obj_type == "user_group":
        name = group_names_by_id.get(condition.referenced_object_id)
        if not name:
            raise UncompilablePolicyError("This condition's referenced user group no longer exists.")
        if op == "equal":
            return f"member == {name}"
        elif op == "not_equal":
            return f"member != {name}"
        raise UncompilablePolicyError(f"Operator '{op}' is not compilable for user_group.")

    elif obj_type == "device":
        name = device_names_by_id.get(condition.referenced_object_id)
        if not name:
            raise UncompilablePolicyError("This condition's referenced device no longer exists.")
        if op == "equal":
            return f"device == {name}"
        elif op == "not_equal":
            return f"device != {name}"
        raise UncompilablePolicyError(f"Operator '{op}' is not compilable for device.")

    elif obj_type == "device_group":
        member_names = device_names_by_group_id.get(condition.referenced_object_id, [])
        if not member_names:
            raise UncompilablePolicyError("This condition's referenced device group has no members, or no longer exists.")
        if op == "equal":
            or_chain = " || ".join(f"device == {n}" for n in member_names)
            return f"({or_chain})" if len(member_names) > 1 else or_chain
        elif op == "not_equal":
            and_chain = " && ".join(f"device != {n}" for n in member_names)
            return f"({and_chain})" if len(member_names) > 1 else and_chain
        raise UncompilablePolicyError(f"Operator '{op}' is not compilable for device_group.")

    elif obj_type == "source_ip":
        if op == "equal":
            return f"nac == {condition.value}"
        elif op == "not_equal":
            return f"nac != {condition.value}"
        elif op in ("is_in_cidr", "is_not_in_cidr"):
            acl_name = f"acl_cond_{str(condition.id).replace('-', '')[:12]}"
            acl_blocks_out.append(f"    acl {acl_name} {{ if (nac == {condition.value}) permit deny }}\n")
            reference_op = "==" if op == "is_in_cidr" else "!="
            return f"acl {reference_op} {acl_name}"
        raise UncompilablePolicyError(f"Operator '{op}' is not compilable for source_ip.")

    raise UncompilablePolicyError(f"Unknown condition object type '{obj_type}'.")


def _compile_condition_group_tree(
    db: Session,
    group: PolicyConditionGroup,
    *,
    group_names_by_id: dict,
    device_names_by_id: dict,
    device_names_by_group_id: dict,
    acl_blocks_out: list[str],
) -> str:
    """
    Recursively compiles a condition-tree group into a tac_plus-ng
    boolean expression. AND -> `&&`, OR -> `||` (both confirmed --
    already used by the legacy compiler and the official upstream
    sample's own multi-condition rules). NOT is NOT yet compilable:
    `!` has no confirmed tac_plus-ng syntax the way `&&`/`||`/`==`/`!=`
    now do -- a NOT group anywhere in the tree makes the WHOLE policy
    uncompilable (see UncompilablePolicyError's docstring for what
    that means in practice: excluded from the ruleset, not faked).
    """
    child_conditions = (
        db.query(PolicyCondition).filter(PolicyCondition.group_id == group.id).order_by(PolicyCondition.order.asc()).all()
    )
    child_groups = (
        db.query(PolicyConditionGroup)
        .filter(PolicyConditionGroup.parent_group_id == group.id)
        .order_by(PolicyConditionGroup.order.asc())
        .all()
    )

    clauses = []
    for cond in child_conditions:
        clauses.append(_compile_condition_leaf(
            cond,
            group_names_by_id=group_names_by_id,
            device_names_by_id=device_names_by_id,
            device_names_by_group_id=device_names_by_group_id,
            acl_blocks_out=acl_blocks_out,
        ))
    for child_group in child_groups:
        sub_expr = _compile_condition_group_tree(
            db, child_group,
            group_names_by_id=group_names_by_id,
            device_names_by_id=device_names_by_id,
            device_names_by_group_id=device_names_by_group_id,
            acl_blocks_out=acl_blocks_out,
        )
        clauses.append(f"({sub_expr})")

    if not clauses:
        raise UncompilablePolicyError("An empty condition group cannot be compiled.")

    if group.logical_operator == "AND":
        return " && ".join(clauses)
    elif group.logical_operator == "OR":
        return " || ".join(clauses)
    elif group.logical_operator == "NOT":
        raise UncompilablePolicyError(
            "NOT groups have no confirmed tac_plus-ng syntax ('!' has not been confirmed) and cannot be compiled yet."
        )
    raise UncompilablePolicyError(f"Unknown logical operator '{group.logical_operator}'.")


def resolve_condition_expression(
    db: Session,
    policy: Policy,
    *,
    group_names_by_id: dict,
    device_names_by_id: dict,
    device_names_by_group_id: dict,
    acl_blocks_out: list[str],
) -> str | None:
    """
    The single dispatch point between the legacy flat-field model and
    the new condition-tree model for compilation -- the SAME switch
    app.services.policy_engine.evaluate() uses for evaluation
    (condition_engine.has_condition_tree()), so a policy is compiled
    using the identical model it's evaluated/simulated under; the two
    can never diverge on which model a given policy is using. Can
    raise UncompilablePolicyError for a tree-model policy -- the
    caller (compile_candidate) must catch this per policy.
    """
    if condition_engine.has_condition_tree(db, policy):
        root = condition_engine.get_root_group(db, policy)
        if root is None:
            raise UncompilablePolicyError("This policy's condition tree is missing its root group.")
        return _compile_condition_group_tree(
            db, root,
            group_names_by_id=group_names_by_id,
            device_names_by_id=device_names_by_id,
            device_names_by_group_id=device_names_by_group_id,
            acl_blocks_out=acl_blocks_out,
        )
    return _condition_expression(
        policy,
        group_names_by_id=group_names_by_id,
        device_names_by_id=device_names_by_id,
        device_names_by_group_id=device_names_by_group_id,
    )


_DEVICE_OVERRIDE_PROFILE_NAME = "device_override_full_access"


def _device_override_profile_block() -> str:
    """
    Single shared profile for EVERY device access grant -- confirmed
    syntax, identical structure to _policy_block's own confirmed
    `profile { script { if (service == shell) { if (cmd == "") {
    set priv-lvl = N } ... } } }` shape, just with priv-lvl fixed at
    15 and no command restrictions at all (no CommandRule entries
    anywhere in this profile), matching the feature's own "without
    any limitation" requirement exactly.
    """
    return (
        f"    profile {_DEVICE_OVERRIDE_PROFILE_NAME} {{\n"
        "        script {\n"
        "            if (service == shell) {\n"
        "                if (cmd == \"\") {\n"
        "                    set priv-lvl = 15\n"
        "                }\n"
        "                permit\n"
        "            }\n"
        "        }\n"
        "    }\n"
    )


